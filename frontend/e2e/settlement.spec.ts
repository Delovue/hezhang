import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { api, createActivity, expenseForm, headers, join, register } from './helpers'

async function settlement(page: Page) {
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByRole('button', { name: '结算与付款', exact: true }).click()
  await expect(page.locator('.balance-card').first()).toBeVisible()
}
async function pay(page: Page, amount: string) {
  await page.getByRole('button', { name: '登记已付款', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '登记已付款' })
  await dialog.getByLabel('付款金额（元）').fill(amount)
  await dialog.getByRole('button', { name: '提交付款登记' }).click()
  await expect(dialog).not.toBeVisible()
}
async function action(page: Page, label: string) {
  await page.getByRole('button', { name: label, exact: true }).first().click()
  await page.getByRole('button', { name: '确认操作', exact: true }).click()
}
async function seal(page: Page) {
  await page.getByRole('button', { name: '封账并开始结算' }).click()
  await page.getByRole('button', { name: '确认继续' }).click()
  await expect(page.locator('.detail-title')).toContainText('结算中')
}

