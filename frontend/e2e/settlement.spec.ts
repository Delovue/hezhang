test('an empty activity settles immediately and can be archived', async ({ page }) => {
  await register(page, '小王'); await createActivity(page, '空活动')
  await settlement(page)
  await page.getByRole('button', { name: '封账并开始结算' }).click()
  await page.getByRole('button', { name: '确认继续' }).click()
  await expect(page.locator('.detail-title')).toContainText('已结清')
  await page.getByRole('button', { name: '归档活动', exact: true }).click()
  await page.getByRole('button', { name: '确认继续' }).click()
  await expect(page.locator('.detail-title')).toContainText('已归档')
})

test('retry after a committed payment response is lost creates exactly one payment', async ({ page, browser, request }) => {
  const account = await register(page, '收款人'); const id = await createActivity(page, '付款重试')
  const code = await page.getByTestId('invite-code').innerText()
  const context = await browser.newContext()
  try {
    const payer = await context.newPage(); await register(payer, '付款人'); await join(payer, code)
    await page.getByRole('button', { name: '刷新', exact: true }).click()
    const expense = await expenseForm(page, '餐费', '10')
    await expense.getByRole('button', { name: '保存费用' }).click()
    await expect(expense).not.toBeVisible(); await settlement(page); await seal(page)
    await settlement(payer)
    let first = true; const keys: string[] = []
    await payer.route(`**/activities/${id}/payments`, async route => {
      if (route.request().method() !== 'POST') return route.continue()
      keys.push(route.request().postDataJSON().request_id)
      if (first) { first = false; await route.fetch(); await route.abort('failed') } else await route.continue()
    })
    await payer.getByRole('button', { name: '按此建议登记' }).click()
    const dialog = payer.getByRole('dialog', { name: '登记已付款' })
    await expect(dialog.getByLabel('付款金额（元）')).toHaveValue('5.00')
    await dialog.getByRole('button', { name: '提交付款登记' }).click()
    await expect(dialog.getByRole('button', { name: '重试原付款' })).toBeVisible()
    await expect(dialog.getByLabel('付款金额（元）')).toBeDisabled()
    await dialog.getByRole('button', { name: '重试原付款' }).click()
    await expect(payer.locator('.payment-card')).toHaveCount(1)
    expect(keys).toHaveLength(2); expect(keys[0]).toBe(keys[1])
    const rows = await (await request.get(`${api}/activities/${id}/payments`, { headers: await headers(request, account) })).json()
    expect(rows).toHaveLength(1); expect(rows[0].amount_cents).toBe(500)
  } finally { await context.close() }
})
